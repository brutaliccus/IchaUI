-- Keys that place a frame. Only filled as a group, so a saved partial anchor is not
-- mixed with baked coordinates.
IchaUI_BakedPosGroups = {
    x = "p", y = "p", point = "p", relPoint = "p", rel = "p", relTo = "p",
    buffX = "b", buffY = "b", buffPoint = "b", buffRel = "b",
    debuffX = "d", debuffY = "d", debuffPoint = "d", debuffRel = "d",
    zoneX = "z", zoneY = "z", zonePoint = "z", zoneRelPoint = "z", zoneAnchor = "z",
    clockX = "c", clockY = "c", clockPoint = "c", clockRelPoint = "c", clockAnchor = "c",
}

-- Tables copied whole when missing and never merged into when present.
IchaUI_BakedAtomic = {
    fill = true, gold = true, trackerLoose = true, trackerOnYou = true,
    smartMarkOrder = true, smartMarkFriendOrder = true,
    smartMarkOff = true, smartMarkFriendOff = true,
    barPlace = { ["*"] = true },
    barPopPos = true, drawerPopPos = true,
    minimapButtons = { buttons = { ["*"] = true } },
    uf = { raidDebuffs = true },
    dispel = { order = true },
}

function IchaUI_BakedCopy(src)
    if type(src) ~= "table" then return src end
    local dst = {}
    local k, v
    for k, v in pairs(src) do
        if type(v) == "table" then
            dst[k] = IchaUI_BakedCopy(v)
        else
            dst[k] = v
        end
    end
    return dst
end

function IchaUI_BakedFill(dst, src, atomic)
    if type(dst) ~= "table" or type(src) ~= "table" then return end
    local groups = IchaUI_BakedPosGroups
    local has = {}
    local k, v, g, cur, node
    for k in pairs(dst) do
        g = groups[k]
        if g then has[g] = true end
    end
    for k, v in pairs(src) do
        cur = dst[k]
        if cur == nil then
            g = groups[k]
            if not (g and has[g]) then
                dst[k] = IchaUI_BakedCopy(v)
            end
        elseif type(cur) == "table" and type(v) == "table" then
            node = nil
            if type(atomic) == "table" then
                node = atomic[k]
                if node == nil then node = atomic["*"] end
            end
            if node ~= true then
                IchaUI_BakedFill(cur, v, node)
            end
        end
    end
end

-- Baked value at a path, e.g. IchaUI_BakedGet("minimap", "size"). Tables come back copied.
function IchaUI_BakedGet(a, b, c, d)
    local t = IchaUI_BakedDefaults
    local keys = { a, b, c, d }
    local i
    for i = 1, 4 do
        if keys[i] == nil then break end
        if type(t) ~= "table" then return nil end
        t = t[keys[i]]
    end
    return IchaUI_BakedCopy(t)
end

function IchaUI_ApplyBakedDefaults()
    if type(IchaUIDB) ~= "table" then IchaUIDB = {} end
    IchaUI_BakedFill(IchaUIDB, IchaUI_BakedDefaults, IchaUI_BakedAtomic)
    return IchaUIDB
end

if IchaUIDB == nil then
    IchaUIDB = IchaUI_BakedCopy(IchaUI_BakedDefaults)
end

-- Shaman-only features (totems, recall, imbue, shield) check this. An unknown class
-- (client has no player data yet) counts as shaman so nothing is dropped too early.
function IchaUI_IsShaman()
    if not IchaUI_PlayerClass and UnitClass then
        local _, token = UnitClass("player")
        if type(token) == "string" and token ~= "" then
            IchaUI_PlayerClass = string.upper(token)
        end
    end
    if not IchaUI_PlayerClass then return true end
    return IchaUI_PlayerClass == "SHAMAN"
end

-- Other classes: silence shaman-module frames (no events, no OnUpdate, hidden).
-- True when the frames were stood down.
function IchaUI_ShamanStandDown(a, b, c, d, e, f)
    if IchaUI_IsShaman() then return false end
    local list = { a, b, c, d, e, f }
    local i
    for i = 1, 6 do
        local fr = list[i]
        if fr then
            if fr.UnregisterAllEvents then fr:UnregisterAllEvents() end
            if fr.SetScript then fr:SetScript("OnUpdate", nil) end
            if fr.Hide then fr:Hide() end
        end
    end
    return true
end

